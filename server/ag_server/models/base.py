"""Declarative base, naming convention and column helpers for the models.

Conventions from `docs/schema.md`: UUID primary keys (client-generated UUIDv7
for device-originated rows, server-generated otherwise), `timestamptz`
everywhere, PostgreSQL enums named `<table>_<column>`, JSONB for documents
validated by the pydantic models in `ag_shared`.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any, Final

from sqlalchemy import DateTime, Enum, ForeignKey, MetaData, Uuid, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Stable constraint names, so autogenerate can compare them and migrations can
# drop them by name.
NAMING_CONVENTION: Final = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Any: JSONB documents hold arbitrary JSON; their shape is validated by the
# pydantic models in ag_shared at the edges, not by the ORM.
JsonObject = dict[str, Any]
JsonList = list[Any]


class Base(DeclarativeBase):
    """Base of every AttentionGuard table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def _enum_values(enum_cls: type[StrEnum]) -> list[str]:
    return [member.value for member in enum_cls]


def pg_enum(enum_cls: type[StrEnum], table: str, column: str) -> Enum:
    """A native PostgreSQL enum named `<table>_<column>` storing the members' values."""
    return Enum(
        enum_cls,
        name=f"{table}_{column}",
        values_callable=_enum_values,
        native_enum=True,
        create_constraint=False,
    )


def server_uuid_pk() -> Mapped[uuid.UUID]:
    """Primary key generated by the database (rows created on the server)."""
    return mapped_column(Uuid, primary_key=True, server_default=text("gen_random_uuid()"))


def client_uuid_pk() -> Mapped[uuid.UUID]:
    """Primary key supplied by the workstation (UUIDv7): the ingest idempotency key."""
    return mapped_column(Uuid, primary_key=True)


def fk(
    target: str,
    *,
    nullable: bool = False,
    ondelete: str | None = None,
    use_alter: bool = False,
    primary_key: bool = False,
    unique: bool | None = None,
) -> Mapped[Any]:
    """A UUID foreign key column. Any: the caller's annotation fixes the Python type.

    `use_alter` breaks a table cycle: the constraint is added after both tables.
    """
    return mapped_column(
        Uuid,
        ForeignKey(target, ondelete=ondelete, use_alter=use_alter),
        nullable=nullable,
        primary_key=primary_key,
        unique=unique,
    )


def created_now() -> Mapped[datetime]:
    """A required `timestamptz` that defaults to the server clock."""
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def tstz(*, nullable: bool = True) -> Mapped[Any]:
    """A `timestamptz` column. Any: the caller's annotation fixes optionality."""
    return mapped_column(DateTime(timezone=True), nullable=nullable)
